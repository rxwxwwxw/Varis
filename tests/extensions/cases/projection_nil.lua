-- Extension regression: projection_nil
relation p(3)
fact p(nil, false, 0) fact p(nil, true, 1) fact p(nil, false, 2)
local it = query p(?x, ?_, ?_)
local row = it()
assert(row and row.x == nil and logic.hasbinding(row, "x"))
assert(logic.binding(row, "x") == nil and not logic.hasbinding(row, "_"))
assert(row.missing == nil)
reject(function() logic.binding(row, "missing") end, "not found")
reject(function() row.x = 2 end, "immutable")
reject(function() row.extra = 2 end, "immutable")
assert(it() == nil and it() == nil)
assert(count(query p(?_, ?_, ?_)) == 1, "ground projection must deduplicate")
assert(count(query p(nil, false, ?v)) == 2)
assert(count(query p(?x, ?x, ?_)) == 0)
