import argparse
import json
import os
import re
import sys
import time
from pathlib import Path

from . import manifest as MF
from . import model as M
from . import runner as R
from .kinds import Ctx

ROOT = MF.ROOT
GOOD = {M.PASS, M.SKIP, M.XFAIL, M.PARTIAL}


def _ctx(args):
    cand = Path(args.candidate or os.environ.get("SUITE_BIN") or ROOT / "bin/dlua")
    ref = Path(args.reference) if args.reference else ROOT / "c-implementation/src/lua"
    if not cand.is_file():
        sys.exit(f"candidate interpreter not found: {cand} (run `make dlua`)")
    return Ctx(ROOT, cand.resolve(), ref.resolve() if ref.is_file() and not args.no_reference else None,
               args.timeout_scale)


def cmd_test(args):
    manifest = MF.load(args.manifest)
    cases, ledger, _ = MF.expand(manifest)
    sel = R.select(cases, args.tier, args.filter, args.suite, args.tag)
    if not sel:
        sys.exit("no cases selected")
    ctx = _ctx(args)
    if args.list:
        for c in sel:
            print(f"{c.tier:<6} {c.kind:<10} {c.id}")
        return 0
    print(f"tier={args.tier} cases={len(sel)} candidate={ctx.candidate}"
          f" reference={'yes' if ctx.reference else 'no'} jobs={args.jobs}", flush=True)
    R.prepare(sel, ctx)
    start = time.perf_counter()
    quiet = args.quiet

    def show(r):
        if not (quiet and r.status in GOOD):
            print(f"[{r.status.upper():<9}] {r.id} ({r.seconds:.2f}s)" + (f"  {r.detail}" if r.detail and r.status != M.PASS else ""),
                  flush=True)

    raw = R.execute(sel, ctx, args.jobs, show)
    # Suites that expand to many results are verified against their declared counts.
    results = R.apply_ledger(raw, ledger)
    for suite in manifest.get("suite", []):
        if "expect_results" in suite and (not args.filter) and suite["id"] in {c.suite for c in sel}:
            got = sum(1 for r in results if r.suite == suite["id"])
            if got != suite["expect_results"]:
                results.append(M.Result(f"{suite['id']}.count", suite["id"], M.FAIL, 0,
                                        f"expected {suite['expect_results']} results, got {got}"))
    wall = time.perf_counter() - start
    rep = R.report(results, ctx, args.tier, wall)
    if args.json:
        Path(args.json).write_text(json.dumps(rep, indent=2) + "\n")
    bad = [r for r in results if r.status not in GOOD]
    print("\n" + ", ".join(f"{n} {k}" for k, n in sorted(rep["counts"].items())) + f"  [{wall:.1f}s]")
    for r in sorted(bad, key=lambda r: r.id):
        print(f"  FAILED {r.id}: {r.detail[:300]}")
    return 1 if bad else 0


def cmd_check(args):
    manifest = MF.load(args.manifest)
    cases, ledger, counts = MF.expand(manifest)
    ids = {c.id for c in cases}
    problems = []
    for lid in ledger:
        if lid not in ids and not any(c.startswith(lid.split(".")[0] + ".") for c in ids):
            problems.append(f"ledger entry {lid} matches no case/suite")
    for c in cases:
        p = c.params.get("path")
        if p and not (ROOT / p).exists():
            problems.append(f"{c.id}: missing {p}")
    print(f"{len(cases)} cases in {len(counts)} suites: " + ", ".join(f"{k}={v}" for k, v in counts.items()))
    for p in problems:
        print("  " + p, file=sys.stderr)
    return 1 if problems else 0


def cmd_trace(args):
    import tomllib
    reqs = tomllib.loads((ROOT / "tests/requirements.toml").read_text())["requirement"]
    cases, _, _ = MF.expand(MF.load(args.manifest))
    ids = {c.id for c in cases}
    unit_src = "\n".join(p.read_text() for p in (ROOT / "tests/unit").glob("*.d"))
    lines, problems = [], []
    group = None
    for r in reqs:
        ev = []
        for e in r.get("evidence", []):
            if e.startswith("unit:"):
                ok = re.search(r"\b" + re.escape(e[5:]) + r"\s*\(", unit_src) is not None
            else:
                ok = e in ids
            ev.append((e, ok))
            if not ok:
                problems.append(f"{r['id']}: unresolved evidence {e}")
        if not ev:
            problems.append(f"{r['id']}: no evidence")
        if r["spec"] != group:
            group = r["spec"]
            lines += [f"\n## {group}\n", "| Requirement | Evidence |", "| --- | --- |"]
        lines.append(f"| {r['id']} {r['title']} | " + ", ".join(f"`{e}`" for e, _ in ev) + " |")
    doc = ("# Requirement traceability\n\nGenerated by `python3 tools/suite trace --write`; "
           "source of truth is `tests/requirements.toml`. `unit:` names are D test functions in "
           "`tests/unit`; others are suite case ids.\n" + "\n".join(lines) + "\n")
    if args.write:
        (ROOT / "tests/TRACEABILITY.md").write_text(doc)
    elif args.verify:
        cur = (ROOT / "tests/TRACEABILITY.md").read_text() if (ROOT / "tests/TRACEABILITY.md").exists() else ""
        if cur != doc:
            problems.append("tests/TRACEABILITY.md is stale (run `python3 tools/suite trace --write`)")
    for p in problems:
        print(p, file=sys.stderr)
    print(f"{len(reqs)} requirements, {len(problems)} problem(s)")
    return 1 if problems else 0


def build_parser():
    ap = argparse.ArgumentParser(prog="suite")
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("test", help="run the test suite")
    t.add_argument("--tier", choices=M.TIERS, default="fast")
    t.add_argument("--filter", action="append", default=[], help="substring of case id (repeatable)")
    t.add_argument("--suite", action="append", default=[])
    t.add_argument("--tag", action="append", default=[])
    t.add_argument("--candidate")
    t.add_argument("--reference")
    t.add_argument("--no-reference", action="store_true")
    t.add_argument("--jobs", type=int, default=min(4, os.cpu_count() or 1))
    t.add_argument("--timeout-scale", type=float, default=1.0)
    t.add_argument("--json")
    t.add_argument("--list", action="store_true")
    t.add_argument("--quiet", "-q", action="store_true", help="only print non-passing results")
    t.add_argument("--manifest")
    t.set_defaults(fn=cmd_test)
    c = sub.add_parser("check", help="validate the manifest against the tree")
    c.add_argument("--manifest")
    c.set_defaults(fn=cmd_check)
    r = sub.add_parser("trace", help="requirement traceability")
    r.add_argument("--manifest")
    r.add_argument("--write", action="store_true")
    r.add_argument("--verify", action="store_true")
    r.set_defaults(fn=cmd_trace)
    return ap


def main(argv=None):
    args = build_parser().parse_args(argv)
    return args.fn(args)
