ROOT = MF.ROOT
GOOD = {M.PASS, M.SKIP, M.XFAIL, M.PARTIAL}


def _ctx(args):
    cand = Path(args.candidate or os.environ.get("SUITE_BIN") or ROOT / "bin/dlua")
    ref = Path(args.reference) if args.reference else ROOT / "c-implementation/src/lua"
    if not cand.is_file():
        sys.exit(f"candidate interpreter not found: {cand} (run `make dlua`)")
    return Ctx(ROOT, cand.resolve(), ref.resolve() if ref.is_file() and not args.no_reference else None,
               args.timeout_scale)


def cmd_test(args):
    manifest = MF.load(args.manifest)
    cases, ledger, _ = MF.expand(manifest)
    sel = R.select(cases, args.tier, args.filter, args.suite, args.tag)
    if not sel:
        sys.exit("no cases selected")
    ctx = _ctx(args)
    if args.list:
        for c in sel:
            print(f"{c.tier:<6} {c.kind:<10} {c.id}")
        return 0
    print(f"tier={args.tier} cases={len(sel)} candidate={ctx.candidate}"
          f" reference={'yes' if ctx.reference else 'no'} jobs={args.jobs}", flush=True)
    R.prepare(sel, ctx)
    start = time.perf_counter()
    quiet = args.quiet

    def show(r):
        if not (quiet and r.status in GOOD):
            print(f"[{r.status.upper():<9}] {r.id} ({r.seconds:.2f}s)" + (f"  {r.detail}" if r.detail and r.status != M.PASS else ""),
                  flush=True)

    raw = R.execute(sel, ctx, args.jobs, show)
    # Suites that expand to many results are verified against their declared counts.
    results = R.apply_ledger(raw, ledger)
    for suite in manifest.get("suite", []):
        if "expect_results" in suite and (not args.filter) and suite["id"] in {c.suite for c in sel}:
            got = sum(1 for r in results if r.suite == suite["id"])
            if got != suite["expect_results"]:
                results.append(M.Result(f"{suite['id']}.count", suite["id"], M.FAIL, 0,
                                        f"expected {suite['expect_results']} results, got {got}"))
    wall = time.perf_counter() - start
    rep = R.report(results, ctx, args.tier, wall)
    if args.json:
        Path(args.json).write_text(json.dumps(rep, indent=2) + "\n")
    bad = [r for r in results if r.status not in GOOD]
    print("\n" + ", ".join(f"{n} {k}" for k, n in sorted(rep["counts"].items())) + f"  [{wall:.1f}s]")
    for r in sorted(bad, key=lambda r: r.id):
        print(f"  FAILED {r.id}: {r.detail[:300]}")
    return 1 if bad else 0


def cmd_check(args):
    manifest = MF.load(args.manifest)
    cases, ledger, counts = MF.expand(manifest)
    ids = {c.id for c in cases}
    problems = []
    for lid in ledger:
        if lid not in ids and not any(c.startswith(lid.split(".")[0] + ".") for c in ids):
            problems.append(f"ledger entry {lid} matches no case/suite")
    for c in cases:
        p = c.params.get("path")
        if p and not (ROOT / p).exists():
            problems.append(f"{c.id}: missing {p}")
    print(f"{len(cases)} cases in {len(counts)} suites: " + ", ".join(f"{k}={v}" for k, v in counts.items()))
    for p in problems:
        print("  " + p, file=sys.stderr)
    return 1 if problems else 0


def cmd_trace(args):
    import tomllib
    reqs = tomllib.loads((ROOT / "tests/requirements.toml").read_text())["requirement"]
    cases, _, _ = MF.expand(MF.load(args.manifest))
    ids = {c.id for c in cases}
    unit_src = "\n".join(p.read_text() for p in (ROOT / "tests/unit").glob("*.d"))
    lines, problems = [], []
    group = None
    for r in reqs:
        ev = []
        for e in r.get("evidence", []):
            if e.startswith("unit:"):
                ok = re.search(r"\b" + re.escape(e[5:]) + r"\s*\(", unit_src) is not None
            else:
                ok = e in ids
            ev.append((e, ok))
            if not ok:
                problems.append(f"{r['id']}: unresolved evidence {e}")
        if not ev:
            problems.append(f"{r['id']}: no evidence")
        if r["spec"] != group:
            group = r["spec"]
            lines += [f"\n## {group}\n", "| Requirement | Evidence |", "| --- | --- |"]
        lines.append(f"| {r['id']} {r['title']} | " + ", ".join(f"`{e}`" for e, _ in ev) + " |")
    doc = ("# Requirement traceability\n\nGenerated by `python3 tools/suite trace --write`; "
           "source of truth is `tests/requirements.toml`. `unit:` names are D test functions in "
           "`tests/unit`; others are suite case ids.\n" + "\n".join(lines) + "\n")
    if args.write:
        (ROOT / "tests/TRACEABILITY.md").write_text(doc)
    elif args.verify:
        cur = (ROOT / "tests/TRACEABILITY.md").read_text() if (ROOT / "tests/TRACEABILITY.md").exists() else ""
        if cur != doc:
            problems.append("tests/TRACEABILITY.md is stale (run `python3 tools/suite trace --write`)")
    for p in problems:
        print(p, file=sys.stderr)
    print(f"{len(reqs)} requirements, {len(problems)} problem(s)")
    return 1 if problems else 0


def cmd_bench(args):
    from . import bench as B
    manifest = B.load_manifest()
    targets = B.load_targets()
    ws = B.workloads(manifest)
    if args.group:
        ws = [w for w in ws if w["group"] in args.group]
    if args.filter:
        ws = [w for w in ws if any(f in w["id"] for f in args.filter)]
    if not ws:
        sys.exit("no workloads selected")
    if args.list:
        for w in ws:
            print(f"{w['kind']:<8} {w['id']}  targets={sorted(set(k for kk in ('goal','gate','floor') for k in targets.get(w['id'], {}).get(kk, {})))}")
        return 0
    cand = Path(args.candidate or os.environ.get("SUITE_BIN") or ROOT / "bin/dlua")
    if not cand.is_file():
        sys.exit(f"candidate not found: {cand}")
    wanted = set(args.compare)
    for w in ws:
        wanted |= B.needed_labels(w, targets.get(w["id"], {}))
    comps = B.resolve_comparators(manifest, sorted(wanted), log=lambda m: print(m, flush=True))
    missing = [l for l, b in comps.items() if b is None]
    if missing:
        print("unavailable comparators: " + ", ".join(missing), flush=True)
    records, derived, failures, behind = [], {}, [], []
    print(f"{'workload':<34}{'time':>9}" + "".join(f"{l[:12]:>14}" for l in sorted(comps)) + "   status", flush=True)
    for w in ws:
        t = targets.get(w["id"], {})
        use = {l: comps[l] for l in (B.needed_labels(w, t) | set(args.compare)) if comps.get(l)}
        rec = B.run_workload(w, cand.resolve(), use, args.runs)
        findings = B.evaluate(rec, t)
        tries = 0
        while args.check and B.hard_failed(findings) and tries < 2 and not args.no_confirm:
            tries += 1
            again = B.run_workload(w, cand.resolve(), use, args.runs)
            f2 = B.evaluate(again, t)
            rec["confirmation"] = rec.get("confirmation", []) + [f2]
            if not B.hard_failed(f2):
                rec, findings = again, f2
                rec["note"] = "first run failed a gate; passed on confirmation re-run"
                break
        rec["findings"] = findings
        records.append(rec)
        derived[w["id"]] = B.derive(rec, None)
        cells = ""
        for l in sorted(comps):
            r = rec["ratios"].get(l)
            cells += f"{r['median']:>13.2f}x" if r else f"{'-':>14}"
        status = []
        if rec["status"] == "error":
            status.append("ERROR " + rec["errors"].get("candidate", "")[:60])
            failures.append(w["id"])
        for k, v in rec["errors"].items():
            if k != "candidate":
                status.append(f"{k}: {v[:50]}")
        if rec.get("errors", {}).get("output"):
            failures.append(w["id"])
        for f in findings:
            if f["ok"] is False:
                status.append(f"{f['kind'].upper()} {f['label']} {f['value']:.2f} vs {f['limit']}")
                if f["kind"] == "goal":
                    behind.append(w["id"])
                elif args.check:
                    failures.append(w["id"])
        if rec.get("noisy"):
            status.append("noisy")
        if rec.get("note"):
            status.append(rec["note"])
        tm = rec["binaries"].get("candidate", {}).get("median", float("nan"))
        print(f"{w['id']:<34}{tm:>8.3f}s{cells}   {'; '.join(status) or 'ok'}", flush=True)
    doc = {"schema": 1, "kind": "bench", "machine": platform.platform(), "arch": platform.machine(),
           "toolchain": B.toolchain_id(), "commit": R.git_commit(ROOT), "runs": args.runs,
           "binaries": {"candidate": identity(cand), **{l: identity(b) for l, b in comps.items() if b}},
           "records": records}
    if args.json:
        Path(args.json).write_text(json.dumps(doc, indent=2) + "\n")
    if args.record:
        d = ROOT / "benchmarks/baselines"
        d.mkdir(exist_ok=True)
        (d / f"{args.record}.json").write_text(json.dumps(doc, indent=2) + "\n")
    if args.derive_targets:
        derived = {k: v for k, v in derived.items() if v}
        Path(args.derive_targets).write_text(B.render_targets(derived) + "\n")
        print(f"wrote {args.derive_targets} ({len(derived)} workloads)")
    print(f"\n{len(records)} workloads; {len(behind)} behind goal" + (f": {', '.join(behind)}" if behind else ""))
    if failures:
        print("FAILED: " + ", ".join(sorted(set(failures))))
    return 1 if failures else 0


def cmd_targets(args):
    """Derive benchmarks/targets.toml from recorded bench JSON files using the §4.3 policy."""
    from . import bench as B
    merged = {}
    for path in args.inputs:
        for rec in json.loads(Path(path).read_text())["records"]:
            if rec.get("status") != "measured":
                continue
            hist = {}
            if args.history and rec["id"].startswith("core."):
                hist = _history_ratios(rec["id"].split(".", 1)[1])
            t = B.derive(rec, hist)
            if t:
                merged[rec["id"]] = t
    Path(args.output).write_text(B.render_targets(merged) + "\n")
    print(f"wrote {args.output}: {len(merged)} workloads")
    return 0


_HIST_NAMES = {"fib": "fibonacci_recursive", "numeric_loop": "numeric_for_loop", "array_access": "table_array_access",
               "hash_access": "table_hash_access", "string_manip": "string_manipulation", "sieve": "sieve_of_eratosthenes"}


def _history_ratios(name):
    """Worst clua ratio among the last recorded history runs (benchmarks/history), if any."""
    worst = {}
    key = _HIST_NAMES.get(name)
    hist = ROOT / "benchmarks/history/2026-10-09-perf/final-execution.json"
    if key and hist.exists():
        d = json.loads(hist.read_text())
        r = d["workloads"].get(key, {}).get("ratio")
        if r:
            worst["clua"] = r
    return worst


def build_parser():
    ap = argparse.ArgumentParser(prog="suite")
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("test", help="run the test suite")
    t.add_argument("--tier", choices=M.TIERS, default="fast")
    t.add_argument("--filter", action="append", default=[], help="substring of case id (repeatable)")
    t.add_argument("--suite", action="append", default=[])
    t.add_argument("--tag", action="append", default=[])
    t.add_argument("--candidate")
    t.add_argument("--reference")
    t.add_argument("--no-reference", action="store_true")
    t.add_argument("--jobs", type=int, default=min(4, os.cpu_count() or 1))
    t.add_argument("--timeout-scale", type=float, default=1.0)
    t.add_argument("--json")
    t.add_argument("--list", action="store_true")
    t.add_argument("--quiet", "-q", action="store_true", help="only print non-passing results")
    t.add_argument("--manifest")
    t.set_defaults(fn=cmd_test)
    b = sub.add_parser("bench", help="run the benchmark suite")
    b.add_argument("--group", action="append", default=[])
    b.add_argument("--filter", action="append", default=[])
    b.add_argument("--candidate")
    b.add_argument("--compare", action="append", default=[], help="extra comparator label")
    b.add_argument("--runs", type=int)
    b.add_argument("--check", action="store_true", help="enforce gates, floors and memory limits")
    b.add_argument("--no-confirm", action="store_true")
    b.add_argument("--json")
    b.add_argument("--record", metavar="LABEL", help="store the result as benchmarks/baselines/LABEL.json")
    b.add_argument("--derive-targets", metavar="FILE")
    b.add_argument("--list", action="store_true")
    b.set_defaults(fn=cmd_bench)
    tg = sub.add_parser("targets", help="derive targets.toml from recorded bench JSON")
    tg.add_argument("inputs", nargs="+")
    tg.add_argument("--output", default=str(ROOT / "benchmarks/targets.toml"))
    tg.add_argument("--history", action="store_true", help="fold in benchmarks/history ratios")
    tg.set_defaults(fn=cmd_targets)
    c = sub.add_parser("check", help="validate the manifest against the tree")
    c.add_argument("--manifest")
    c.set_defaults(fn=cmd_check)
    r = sub.add_parser("trace", help="requirement traceability")
    r.add_argument("--manifest")
    r.add_argument("--write", action="store_true")
    r.add_argument("--verify", action="store_true")
    r.set_defaults(fn=cmd_trace)
    return ap


def main(argv=None):
    args = build_parser().parse_args(argv)
    return args.fn(args)
